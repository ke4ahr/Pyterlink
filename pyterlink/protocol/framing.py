"""LNKCLIENT frame encoding (docs/interlnk_protocol_spec.md section 5).

One frame format, as carried on the wire (logs/ captures) and traced in
Ghidra (project InterLinkRE, LNKSERVER).

**FRAME FORMAT:**

  tag(1) || count(1 or 2 LE) || data(count) || crc(2)

**tag byte** (LNKSERVER LinkProtoHandler 1000:7257):
  - bits 0-1: per-frame sequence counter (mod 4), checked against RAM:0x1d5
              (AND AL,3 at 1000:7276).
  - bit 7:    count-width flag: 1 => 8-bit count, 0 => 16-bit LE count
              (TEST BL,0x80 at 1000:7299). Set when data fits in 0xFF bytes.
  - bit 6:    a 16-bit-count sector-data chunk with another chunk after it
              (multi-sector reads/writes, strace captures s57).
  - bit 2:    retransmission of the same frame after a missed ack (seen only
              as links died; not implemented).
  - bits 3-5: always 0.

**count** (1 or 2 bytes LE): number of data bytes.

**data** (count bytes): a request or reply, or a chunk of sector data.

**crc** (2 bytes): CRC-16/GENIBUS over count+data (the tag is excluded):
poly 0x1021, init 0xFFFF (MOV CX,0xffff at 1000:728f), no reflection, the
tail is `~crc` high byte first; check value for "123456789" is 0xD64E. A
receiver running the same CRC over count+data+crc reaches the residue 0x1D0F
(CMP CX,0x1d0f at 1000:72cc); 0x1D0F is not a byte sequence on the wire.

**Tag echo and ack:** the receiver echoes the tag as `~tag & 0xfb` (NOT AH;
AND AH,0xfb at 1000:7287; tag 0x80 -> echo 0x7b on the wire); the sender then
bursts count, data and crc, and the receiver acks with the tag byte.

References (FP2 InterLinkRE, LNKSERVER):
  - 1000:7257 LinkProtoHandler      -- frame receive (tag/count/data/crc, residue)
  - 1000:722a LinkReadWithTimeout   -- read one byte (18-tick timeout) + CRC update
  - 1000:5b00 LinkCrc16Out          -- transmit-side CRC update
  - 1000:5b21 LinkCrc16Xmit         -- transmit a byte with its CRC update
  - verified byte-exact against recorded captures in both roles
    (replayed through pyterlink during development)
"""


import logging

log = logging.getLogger(__name__)

# Receiver's running CRC over count+data+tail on a good frame.
CRC_RESIDUE = 0x1D0F
# Tag bits (LNKSERVER LinkProtoHandler 1000:7276 / 1000:7299).
COUNTER_MASK = 0x03
LENGTH_FLAG_8BIT = 0x80
# Set on a 16-bit-count data chunk that another chunk follows (multi-sector
# op04 replies and op05 requests move 8 KB per frame; strace captures s57).
MORE_FLAG = 0x40
MAX_MESSAGE_BYTES = 0xFFFF


class FramingError(Exception):
    """Raised for a frame that cannot be encoded."""


def _prng_crc16_table() -> tuple:
    """The LNKCLIENT frame-CRC table (generated by PrngXorshiftInit 1000:71ef;
    used by LinkCrc16Out 1000:5b00 and LinkReadWithTimeout 1000:722a)."""
    table = []
    for i in range(256):
        x = i ^ (i >> 4)
        x = x ^ ((x << 12) & 0xFFFF)
        entry = x ^ ((x & 0xFF) << 5)
        table.append(entry & 0xFFFF)
    return tuple(table)


_PRNG_CRC16_TABLE = _prng_crc16_table()


def _crc16_prng(data: bytes, init: int = 0xFFFF) -> int:
    """LNKCLIENT frame CRC (init 0xFFFF, MOV CX,0xffff at 1000:728f)."""
    crc = init
    for b in data:
        crc = ((crc << 8) & 0xFFFF) ^ _PRNG_CRC16_TABLE[((crc >> 8) ^ b) & 0xFF]
    return crc


def encode_envelope(message: bytes, counter: int, more: bool = False) -> bytes:
    """Build tag + count + message + crc for the 2-bit frame counter.

    Bit 7 of the tag (8-bit count) is set when the message fits in 0xFF
    bytes; `more` (a data chunk with another after it) sets bit 6 and
    forces the 16-bit count. The tail is ~CRC(count+message) emitted high
    byte first, so the receiver's CRC over count+message+tail reaches
    CRC_RESIDUE.
    """
    if not 0 <= counter <= 3:
        raise FramingError(f"counter {counter} out of range 0..3")
    n = len(message)
    if not 1 <= n <= MAX_MESSAGE_BYTES:
        raise FramingError(f"message length {n} out of range")
    tag = counter & COUNTER_MASK
    if more:
        tag |= MORE_FLAG
        count_bytes = bytes([n & 0xFF, (n >> 8) & 0xFF])
    elif n <= 0xFF:
        tag |= LENGTH_FLAG_8BIT
        count_bytes = bytes([n])
    else:
        count_bytes = bytes([n & 0xFF, (n >> 8) & 0xFF])
    inv = (~_crc16_prng(count_bytes + message, 0xFFFF)) & 0xFFFF
    return bytes([tag]) + count_bytes + message + bytes([inv >> 8, inv & 0xFF])
